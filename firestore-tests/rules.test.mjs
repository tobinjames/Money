import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, collection, getDocs, query, where } from 'firebase/firestore';
import fs from 'fs';
const env = await initializeTestEnvironment({ projectId: 'demo-money', firestore: { rules: fs.readFileSync(new URL('../firestore.rules', import.meta.url),'utf8'), host:'127.0.0.1', port:8085 } });
await env.withSecurityRulesDisabled(async c => {
  const db = c.firestore();
  await setDoc(doc(db,'AuthorizedUsers','tobin@example.com'), {email:'tobin@example.com', firstName:'Tobin'});
  await setDoc(doc(db,'AuthorizedUsers','old@example.com'), {email:'old@example.com', isActive:false});
  await setDoc(doc(db,'whitelisted_userlist','spouse@example.com'), {email:'spouse@example.com'});
  await setDoc(doc(db,'AuthorizedUsers','master_whitelist'), {emails:['list@example.com']});
  await setDoc(doc(db,'Transactions','t1'), {amount: 10});
  await setDoc(doc(db,'GeminiInteractionLogs','g1'), {rawSmsContent: 'x'});
});
const ctx = (uid, email, verified=true) => env.authenticatedContext(uid, {email, email_verified: verified}).firestore();
const member = ctx('u1','Tobin@Example.com');
const spouse = ctx('u2','spouse@example.com');
const listed = ctx('u3','list@example.com');
const unverified = ctx('u4','tobin@example.com', false);
const stranger = ctx('u5','evil@example.com');
const inactive = ctx('u6','old@example.com');
const anon = env.unauthenticatedContext().firestore();
let fails = 0;
async function t(name, p) { try { await p; console.log('PASS', name); } catch (e) { fails++; console.log('FAIL', name, e.message); } }
await t('member reads tx', assertSucceeds(getDoc(doc(member,'Transactions','t1'))));
await t('member lists tx', assertSucceeds(getDocs(collection(member,'Transactions'))));
await t('member writes tx', assertSucceeds(setDoc(doc(member,'Transactions','t2'),{amount:5})));
await t('spouse (2nd list) reads tx', assertSucceeds(getDoc(doc(spouse,'Transactions','t1'))));
await t('master list member reads tx', assertSucceeds(getDoc(doc(listed,'Transactions','t1'))));
await t('unverified denied', assertFails(getDoc(doc(unverified,'Transactions','t1'))));
await t('stranger denied', assertFails(getDocs(collection(stranger,'Transactions'))));
await t('inactive denied', assertFails(getDoc(doc(inactive,'Transactions','t1'))));
await t('anon denied', assertFails(getDocs(collection(anon,'Transactions'))));
await t('member reads own allowlist', assertSucceeds(getDoc(doc(member,'AuthorizedUsers','tobin@example.com'))));
await t('stranger reads own (missing) allowlist entry', assertSucceeds(getDoc(doc(stranger,'AuthorizedUsers','evil@example.com'))));
await t('member cannot read other allowlist entry', assertFails(getDoc(doc(member,'AuthorizedUsers','old@example.com'))));
await t('query allowlist by own email', assertSucceeds(getDocs(query(collection(member,'AuthorizedUsers'), where('email','==','tobin@example.com')))));
await t('stranger reads master list denied', assertFails(getDoc(doc(stranger,'AuthorizedUsers','master_whitelist'))));
await t('listed reads master list', assertSucceeds(getDoc(doc(listed,'AuthorizedUsers','master_whitelist'))));
await t('member cannot write allowlist', assertFails(setDoc(doc(member,'AuthorizedUsers','evil@example.com'),{email:'evil@example.com'})));
await t('telemetry closed', assertFails(getDoc(doc(member,'GeminiInteractionLogs','g1'))));
await t('own profile write', assertSucceeds(setDoc(doc(member,'users','u1'),{a:1})));
await t('other profile write denied', assertFails(setDoc(doc(member,'users','u2'),{a:1})));
await t('unknown collection denied', assertFails(getDoc(doc(member,'random','x'))));
await env.cleanup();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails?1:0);
